// Computer Network Lab (BCS502) - Sliding Window Protocol (Go-Back-N ARQ)
import java.util.ArrayList;
import java.util.List;
import java.util.Scanner;

public class SlidingWindow {

    public static void main(String[] args) {
        Scanner input = new Scanner(System.in);

        // 1. Read simulation parameters from the user
        System.out.print("Enter total number of frames: ");
        int totalFrames = input.nextInt();

        System.out.print("Enter sender window size: ");
        int windowSize = input.nextInt();

        System.out.print("Enter frame to lose once (0 for no loss): ");
        int lostFrame = input.nextInt();

        input.close();

        // Validate inputs to prevent infinite loops or invalid frame indices
        if (totalFrames <= 0 || windowSize <= 0 || lostFrame < 0 || lostFrame > totalFrames) {
            System.out.println("Invalid input: frame count and window size must be positive; "
                    + "lost frame must be between 0 and the total number of frames.");
            return;
        }

        // 2. Initialize Sender & Receiver state variables
        int base = 1;           // Oldest unacknowledged frame (start of the sender's window)
        int nextFrame = 1;      // Next frame sequence number to be transmitted
        int expectedFrame = 1;  // Next in-order frame expected by the receiver

        boolean lossOccurred = false; // Ensures the chosen frame is dropped only once
        int transmissions = 0;        // Counts total frame transmissions (initial + retransmitted)

        System.out.println("\n--- Go-Back-N Simulation ---");

        // 3. Main transmission loop: runs until all frames are acknowledged
        while (base <= totalFrames) {
            // Calculate the upper boundary of the current sender window
            int windowEnd = (int) Math.min((long) base + windowSize - 1, totalFrames);

            System.out.println("\nSender window: [" + base + " to " + windowEnd + "]");

            // Holds cumulative ACKs generated by the receiver for the current batch of frames
            List<Integer> acknowledgements = new ArrayList<>();

            // 4. Transmit all unsent frames within the current window
            while (nextFrame <= windowEnd) {
                int frame = nextFrame;
                transmissions++;

                System.out.println("Sender: sends frame " + frame);

                // Simulate frame loss on the channel (only happens on the first attempt)
                if (frame == lostFrame && !lossOccurred) {
                    System.out.println("Channel: frame " + frame + " is LOST");
                    lossOccurred = true;
                } else {
                    // Receiver accepts frames strictly in sequential order
                    if (frame == expectedFrame) {
                        System.out.println("Receiver: accepts frame " + frame);
                        expectedFrame++;
                    } else {
                        // Go-Back-N rule: discard any out-of-order frames after a missing frame
                        System.out.println("Receiver: discards frame " + frame
                                + "; expected frame " + expectedFrame);
                    }

                    // Receiver sends cumulative ACK for the last frame received in order
                    // (ACK 0 means frame 1 has not been received yet)
                    acknowledgements.add(expectedFrame - 1);
                }

                nextFrame++;
            }

            // 5. Process all ACKs arriving back at the sender
            for (int ack : acknowledgements) {
                if (ack >= base) {
                    // Valid new ACK: slide the window forward past the acknowledged frame
                    base = ack + 1;
                    System.out.println("Sender: receives ACK " + ack + "; base moves to " + base);
                } else {
                    // Duplicate ACK: receiver is still waiting for 'base'
                    System.out.println("Sender: receives duplicate ACK " + ack);
                }
            }

            // 6. Timeout & Go-Back-N Retransmission check
            // If 'base' has not caught up to 'nextFrame', at least one frame was lost/unacknowledged
            if (base < nextFrame) {
                System.out.println("TIMEOUT: frame " + base + " is still unacknowledged.");
                System.out.println("Go-Back-N: retransmit frames " + base + " to " + (nextFrame - 1));

                // Reset nextFrame back to 'base' so the entire unacknowledged window is resent
                nextFrame = base;
            }
        }

        // 7. Print summary statistics
        System.out.println("\nAll " + totalFrames + " frames delivered successfully.");
        System.out.println("Total frame transmissions: " + transmissions);
        System.out.println("Retransmissions: " + (transmissions - totalFrames));
    }
}
